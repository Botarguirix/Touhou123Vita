#!/usr/bin/env python3
"""Generate com_vtables.h: method order and argument counts of the COM interfaces
the game uses, read from the public DirectX headers (SokuLib's copies of d3d9.h,
d3dx9effect.h and dinput.h, and MinGW's dsound.h). The order is the vtable layout
the recompiled code indexes, so it must come from the headers, never by hand.

  python recomp/host/gen_vtables.py
"""
from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
HEADERS = [ROOT / "local/SokuLib/directx" / n for n in ("d3d9.h", "d3dx9effect.h", "dinput.h")]
HEADERS.append(Path(r"C:\msys64\ucrt64\include\dsound.h"))
WANTED = ["IDirect3D9", "IDirect3DDevice9", "IDirect3DSwapChain9", "IDirect3DTexture9",
          "IDirect3DSurface9", "ID3DXEffect", "IDirectInput8A", "IDirectInputDevice8A",
          "IDirectSound8", "IDirectSoundBuffer", "IDirectSoundBuffer8", "IDirectSound3DBuffer", "IDirectSound3DListener"]
OUT = Path(__file__).with_name("com_vtables.h")


def interfaces(text: str) -> dict[str, tuple[str, list[tuple[str, int]]]]:
    found = {}
    for m in re.finditer(r"DECLARE_INTERFACE_\(\s*(\w+)\s*,\s*(\w+)\s*\)\s*\{(.*?)\n\s*\};", text, re.S):
        name, base, body = m.group(1), m.group(2), m.group(3)
        body = re.sub(r"/\*.*?\*/", "", body, flags=re.S)
        methods = []
        for sm in re.finditer(r"STDMETHOD_?\((?:[^,()]+,\s*)?(\w+)\)\s*\(\s*(THIS_?)(.*?)\)\s*PURE", body, re.S):
            params = sm.group(3).strip()
            count = 0 if sm.group(2) == "THIS" or not params else params.count(",") + 1
            methods.append((sm.group(1), count + 1))  # + this
        found[name] = (base, methods)
    return found


def main() -> None:
    table: dict[str, tuple[str, list[tuple[str, int]]]] = {
        "IUnknown": ("", [("QueryInterface", 3), ("AddRef", 1), ("Release", 1)])}
    for header in HEADERS:
        table.update({k: v for k, v in interfaces(header.read_text(encoding="latin-1")).items()
                      if k not in table})
    # dinput.h declares the A/W variants through a macro; IDirectInput8A etc. may
    # be spelled IDirectInput8 with the A methods identical in layout.
    aliases = {"IDirectInput8A": "IDirectInput8", "IDirectInputDevice8A": "IDirectInputDevice8"}

    def chain(name: str) -> list[tuple[str, int]]:
        name = name if name in table else aliases.get(name, name)
        if name not in table:
            raise SystemExit(f"interface {name} not found in the headers")
        base, methods = table[name]
        inherited = chain(base) if base and base not in ("", name) else []
        own = [m for m in methods if m[0] not in {x[0] for x in inherited}]
        return inherited + own

    lines = ["/* Generated by recomp/host/gen_vtables.py from public DirectX headers. */",
             "#ifndef T123_COM_VTABLES_H", "#define T123_COM_VTABLES_H", "",
             "typedef struct { const char *name; unsigned char args; } ComMethod;", ""]
    for name in WANTED:
        methods = chain(name)
        lines.append(f"static const ComMethod {name}_methods[] = {{")
        lines += [f'    {{"{m}", {n}}}, /* {i} */' for i, (m, n) in enumerate(methods)]
        lines.append("};")
        lines.append(f"#define {name}_count {len(methods)}u")
        lines.append("")
    lines.append("#endif")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT}: " + ", ".join(f"{n}={len(chain(n))}" for n in WANTED))


if __name__ == "__main__":
    main()
